// 검증된 전체 쿼리에서 교육 목적에 맞는 부분만 빈칸으로 만든다.
// 서로 다른 두 문제를 연결하므로 같은 문장만 외우지 않고 개념을 옮겨 적용한다.
const problems=[...require('./shop.json').problems,...require('./academy.json').problems];
function drills([id,entries]) {
  const p=problems.find(p=>p.id===id);
  if(!p)throw new Error(`연결 문제 없음: ${id}`);
  return entries.map(([answer,title,explanation])=>{
    if(!p.solution.includes(answer))throw new Error(`${id}에 빈칸 대상 없음: ${answer}`);
    return [title,`${p.description}\n\n${title}`,p.solution.replace(answer,'___'),answer,explanation,id];
  });
}
function unit(title,concept,first,second){return {title,concept,query:first[0],queries:[first[0],second[0]],items:[...drills(first),...drills(second)]};}
